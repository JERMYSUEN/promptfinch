let currentLang = 'zh-TW';
let currentScenario = 'coding';
let currentStyle = 'balanced';

const $ = id => document.getElementById(id);

function renderCopy() {
  const dict = COPY[currentLang];
  document.documentElement.lang = currentLang;
  for (const el of document.querySelectorAll('[data-i18n]')) {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  }
  $('lang-toggle').textContent = dict.langSwitch;
}

function renderDemo() {
  const example = EXAMPLES[currentScenario];
  $('demo-input').textContent = example.input;
  $('demo-output').textContent = example.outputs[currentStyle];
  const shieldStrip = $('demo-shield-strip');
  if (example.shield) {
    shieldStrip.hidden = false;
    $('demo-shield-text').textContent = example.shield[currentLang];
  } else {
    shieldStrip.hidden = true;
  }
  const notes = example.notes[currentLang];
  $('demo-notes-summary').textContent = currentLang === 'zh-TW'
    ? `✦ ${notes.length} 項優化重點`
    : `✦ ${notes.length} editing notes`;
  $('demo-notes-list').replaceChildren(...notes.map(item => {
    const li = document.createElement('li');
    li.textContent = item;
    return li;
  }));
}

for (const btn of document.querySelectorAll('.tab')) {
  btn.addEventListener('click', () => {
    currentScenario = btn.dataset.scenario;
    for (const tab of document.querySelectorAll('.tab')) {
      const active = tab === btn;
      tab.classList.toggle('active', active);
      tab.setAttribute('aria-selected', String(active));
    }
    renderDemo();
  });
}

for (const btn of document.querySelectorAll('.style-btn')) {
  btn.addEventListener('click', () => {
    currentStyle = btn.dataset.style;
    for (const s of document.querySelectorAll('.style-btn')) {
      s.classList.toggle('active', s === btn);
    }
    renderDemo();
  });
}

$('lang-toggle').addEventListener('click', () => {
  currentLang = currentLang === 'zh-TW' ? 'en' : 'zh-TW';
  renderCopy();
  renderDemo();
});

$('demo-copy').addEventListener('click', async () => {
  const btn = $('demo-copy');
  try {
    await navigator.clipboard.writeText($('demo-output').textContent);
    btn.textContent = COPY[currentLang].copiedBtn;
    setTimeout(() => { btn.textContent = COPY[currentLang].copyBtn; }, 1400);
  } catch {
    btn.textContent = COPY[currentLang].copyBtn;
  }
});

renderCopy();
renderDemo();
